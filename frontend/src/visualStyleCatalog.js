export function matchingVisualStyle(prompt) {
  if (typeof prompt !== 'string') return null
  return visualStyleCatalog.find(style => style.prompt === prompt.trim()) || null
}

export function videoProjectCover(project) {
  if (!project?.id || !Array.isArray(project.shots)) return ''
  const shot = project.shots.find(item => item.id && item.image && item.image_status === 'completed')
  if (!shot) return ''
  return `/api/video-studio/${encodeURIComponent(project.id)}/images/${encodeURIComponent(shot.id)}?v=${encodeURIComponent(shot.image_version || project.revision || '')}`
}
